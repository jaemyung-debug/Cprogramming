#include <stdio.h>
#include <stdlib.h>

int main(void)
{
    int i;
    int num[5];

    printf("난수의 범위: 0~100\n");

    for (i = 0; i < 5; i++)
    {
        num[i] = rand() % 101;
        printf("난수 출력: %d\n", num[i]);
    }

    return 0;
}