#include <stdio.h>
int main()
{
	double arr[5];
	double* ptr = arr;

	printf("숫자를 입력하세요: ");

	for (int i = 0; i < 5; i++)
	{
		scanf(" %lf", &arr[i]);
	}

	for (int j = 0; j < 5; j++)
	{
		ptr[j] += 2;
	}

	return 0;
}