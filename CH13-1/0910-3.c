#include <stdio.h>

int main(void)
{
    int grade[5];
    int sum = 0;
    int* p = grade;

    for (int i = 0; i < 5; i++)
    {
        printf("성적을 입력하시오: ");
        scanf("%d", p + i);
        sum += *(p + i);
    }

    printf("성적 평균 = %.1f\n", sum / 5.0);

    return 0;
}